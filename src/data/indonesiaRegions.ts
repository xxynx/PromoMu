export function findProvinceByCity(cityName?: string): string {
  const query = (cityName || '').trim().toLowerCase();
  if (!query || query === 'semua wilayah') return 'Jawa Timur';

  const exactMatch = INDONESIA_PROVINCES.find((region) =>
    region.cities.some((c) => c.toLowerCase() === query)
  );
  if (exactMatch) return exactMatch.province;

  const partialMatch = INDONESIA_PROVINCES.find((region) =>
    region.cities.some((c) => c.toLowerCase().includes(query) || query.includes(c.toLowerCase()))
  );
  if (partialMatch) return partialMatch.province;

  if (query.includes('jakarta')) return 'DKI Jakarta';
  if (query.includes('solo') || query.includes('surakarta')) return 'Jawa Tengah';
  if (query.includes('jogja') || query.includes('yogyakarta')) return 'DI Yogyakarta';

  return 'Jawa Timur';
}

export function getCitiesByProvince(provinceName: string): string[] {
  const found = INDONESIA_PROVINCES.find((region) => region.province === provinceName);
  return found ? found.cities : INDONESIA_PROVINCES[0].cities;
}

export function resolveCityInProvince(provinceName: string, cityName?: string): string {
  const provinceCities = getCitiesByProvince(provinceName);
  const query = (cityName || '').trim().toLowerCase();
  if (!query) return provinceCities[0] || '';

  const exact = provinceCities.find((c) => c.toLowerCase() === query);
  if (exact) return exact;

  const partial = provinceCities.find((c) => c.toLowerCase().includes(query));
  if (partial) return partial;

  return provinceCities[0] || '';
}
